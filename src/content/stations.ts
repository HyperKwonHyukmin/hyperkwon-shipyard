/**
 * 장소(스테이션) 내용. 문장을 고칠 때 3D 코드를 건드리지 않도록 여기에만 둔다.
 * 원칙(CLAUDE.md): 공개 자료의 사실만 우리 말로 쓰고 출처를 단다. 자료마다 숫자가 다르면 둘 다 적는다.
 * 좌표: at = 장소 중심(월드 m), cam = 그 장소를 볼 카메라 위치. x 가 클수록 바다 쪽.
 */

export interface Source {
  label: string;
  url: string;
}
export interface Fact {
  text: string;
  source: Source;
}
/** 블록(또는 부재)이 이 장소로 들어오거나(in) 나가는(out) 흐름. to = 상대 장소 id */
export interface Flow {
  dir: 'in' | 'out';
  text: string;
  to: string;
}
export interface Station {
  id: string;
  name: string;
  /** 공식 건조 공정 12단계 가운데 이 장소의 단계(없으면 빈 배열) */
  processes: string[];
  summary: string;
  facts: Fact[];
  at: [number, number, number];
  cam: [number, number, number];
  /** 블록 흐름(패널 '블록 흐름', 지도 화살표, 도로 트랜스포터 경로가 out 흐름에서 나온다) */
  flow?: Flow[];
  /** 빠른 견학 한 바퀴(quicktour.ts)에서 보여 줄 한 줄 — 지금 화면에서 일어나는 일 */
  quick?: string;
  /** 카메라가 바라볼 점(없으면 at). 오른쪽 설명 패널에 가리지 않게 건물을 화면 왼쪽으로 옮길 때 */
  look?: [number, number, number];
  /** 단계 바(아래 칩)에 쓰는 두세 글자 이름 */
  short?: string;
  /** 휴대폰(폭 700px 이하) 시점. 세로 화면은 가로 시야가 좁고 설명 패널이 아래에 있어, 넓은 대상을 보는 장소만 따로 둔다 */
  phoneView?: { cam: [number, number, number]; look: [number, number, number] };
  /** 쉽게 말하면: 처음 보는 사람에게 비유 한두 문장 */
  easy?: string;
  /** 현장 포인트: 엔지니어가 보는 핵심(일반 조선 공학 지식, 이 회사 내부 자료 아님) */
  points?: string[];
  /** 앞뒤 공정과의 연결: 이 장소의 품질이 다음 공정에 주는 영향(현장 사람용) */
  link?: string;
  /** 깊이 보기: 경력자용 쟁점(일반 조선 공학·공개 국제 기준만) */
  deep?: string[];
}

